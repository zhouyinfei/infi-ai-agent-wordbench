-- 手动初始化，重复执行不覆盖用户数据。
CREATE DATABASE IF NOT EXISTS infi_agent CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE infi_agent;
CREATE TABLE IF NOT EXISTS sys_user (
  id BIGINT NOT NULL AUTO_INCREMENT COMMENT '用户ID',
  username VARCHAR(32) NOT NULL COMMENT '登录名',
  password_hash VARCHAR(100) NOT NULL COMMENT 'BCrypt密码摘要',
  nickname VARCHAR(50) NOT NULL COMMENT '昵称',
  email VARCHAR(100) NULL COMMENT '邮箱',
  role VARCHAR(16) NOT NULL DEFAULT 'USER' COMMENT 'USER或ADMIN',
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1启用0禁用',
  auth_version BIGINT NOT NULL DEFAULT 0 COMMENT '凭证版本',
  gmt_create DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  gmt_modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '修改时间',
  PRIMARY KEY (id),
  UNIQUE KEY uk_username (username)
) COMMENT='平台用户';
